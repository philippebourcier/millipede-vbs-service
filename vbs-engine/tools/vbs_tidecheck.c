/*
 * vbs_tidecheck -- how much of the geophysical tide survives the VBS spatial interpolation?
 *
 * Spec §4.2 addendum asks for solid Earth tide, pole tide and ocean tide loading (OTL) on the
 * physical base coordinates. Before writing that into the engine it is worth measuring what
 * it buys, because the VBS already performs a spatial interpolation across the cluster
 * (§4.5), and a displacement field that is planar over the cluster footprint is removed by
 * that interpolation whether or not anyone models it.
 *
 * So for each case this reports two numbers per ENU component, over a 14-day span (long
 * enough to cover the spring-neap beat):
 *
 *   raw    = max |d(vbs) - d(master)|            what an unmodelled tide puts into the
 *                                                network EKF's double differences
 *   resid  = max |d(vbs) - planefit(cluster)|    what survives the §4.5 interpolation and
 *                                                therefore reaches the rover
 *
 * `resid` is the number that decides whether modelling the tide changes the delivered
 * position. `raw` is the number that decides whether it helps the network's own ambiguity
 * resolution. They differ by orders of magnitude and conflating them is how this correction
 * gets over-specified.
 *
 * Also reports the plane fit's leverage at the VBS -- A^-1[0,0], the variance inflation of
 * the fitted value there. It is ~1/n inside a well-spread cluster and grows without bound as
 * the fit is asked to extrapolate or as the stations approach collinearity, which separates
 * "the field really is non-planar here" from "the plane fit is badly posed". Rows with a
 * large leverage are geometry artefacts, not physics.
 *
 * Usage:  vbs_tidecheck <opt> < cases
 *
 *   <opt> is tidedisp()'s bitmask, NOT prcopt_t::tidecorr -- see the note in main().
 *         1 = solid earth tide, 2 = ocean tide loading, 4 = pole tide,
 *         8 = express the displacement relative to a mean-tide rather than a
 *             conventional-tide-free coordinate (see DECISIONS.md D23 on the convention).
 *
 * Input on stdin, generated by data/scripts/tide_report.py:
 *
 *   CASE <id> <label> <n>
 *   V <x> <y> <z> <66 ocean-loading values>
 *   C <x> <y> <z> <66 ocean-loading values>     x n
 *
 * The 66 values are tidedisp()'s `odisp` layout. Emit zeros when no BLQ coefficients are
 * available for a site: the OTL term then contributes nothing and the solid/pole results are
 * unaffected.
 */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "rtklib.h"

#define MAXCL		8
#define NODISP		66
#define SPAN_DAYS	14
#define STEP_S		300.0

/*
 * Least-squares plane d = a + b*E + c*N over the cluster, evaluated at the VBS (E = N = 0),
 * so the fitted value is just `a`. This is the same linear interpolation spec §4.5 specifies
 * as the baseline method, which is the point: it has to be the *same* operator the engine
 * will apply, or the residual measured here says nothing about the engine.
 */
static double planefit_at_vbs(const double *e, const double *n, const double *v, int m,
	double *leverage) {
	double A[3 * 3] = {0}, b[3] = {0}, x[3];
	int i;

	for (i = 0; i < m; i++) {
		double g[3] = {1.0, e[i], n[i]};
		int r, c;

		for (r = 0; r < 3; r++) {
			for (c = 0; c < 3; c++)
				A[r + c * 3] += g[r] * g[c];
			b[r] += g[r] * v[i];
		}
	}
	/* matinv() returns the LAPACK info word: 0 is success, not failure. */
	if (m < 3 || matinv(A, 3) != 0) {
		double s = 0.0;			/* degenerate: fall back to the cluster mean */

		for (i = 0; i < m; i++)
			s += v[i];
		*leverage = m ? 1.0 / m : 0.0;
		return m ? s / m : 0.0;
	}
	*leverage = A[0];
	matmul("NN", 3, 1, 3, 1.0, A, b, 0.0, x);
	return x[0];
}

static int read_site(double *xyz, double *odisp) {
	int i;

	if (scanf("%lf %lf %lf", &xyz[0], &xyz[1], &xyz[2]) != 3)
		return 0;
	for (i = 0; i < NODISP; i++)
		if (scanf("%lf", &odisp[i]) != 1)
			return 0;
	return 1;
}

int main(int argc, char **argv) {
	char tag[16], id[32], label[32];
	static erp_t erp;
	int opt, ncl;

	if (argc < 2) {
		fprintf(stderr, "usage: %s <tidedisp-bitmask> < cases\n", argv[0]);
		return 1;
	}
	opt = atoi(argv[1]);

	/*
	 * tidedisp()'s `opt` is a bitmask; prcopt_t::tidecorr is an enum documented as
	 * "0:off, 1:solid, 2:solid+otl+pole". Both MRTKLIB's and RTKLIB-EX's relative-mode
	 * zdres() pass tidecorr straight through as the bitmask, so configuring tidecorr=2 in
	 * relative mode selects bit 2 alone -- OTL only, with the solid Earth tide and pole
	 * tide switched *off*. MRTKLIB's PPP path spells the intended mapping out
	 * (`opt->tidecorr == 1 ? 1 : 7`); the relative path does not. This tool therefore
	 * takes the bitmask directly and never the enum, and so must the engine.
	 */
	printf("# tidedisp bitmask %d (1=solid 2=otl 4=pole 8=mean-tide reference)\n", opt);
	printf("# span %d days from 2024-10-10 at %.0f s; all figures mm\n", SPAN_DAYS, STEP_S);
	printf("%-8s %-10s %3s  %-23s  %-23s %6s\n", "case", "label", "n",
	    "raw |vbs-master| E/N/U", "resid |vbs-planefit| E/N/U", "lev");

	while (scanf("%15s", tag) == 1) {
		double vxyz[3], vod[NODISP], cxyz[MAXCL][3], cod[MAXCL][NODISP];
		double raw[3] = {0}, res[3] = {0}, lev = 0.0;
		gtime_t t;
		int i, k, step;

		if (strcmp(tag, "CASE") != 0)
			continue;
		if (scanf("%31s %31s %d", id, label, &ncl) != 3)
			break;
		if (ncl > MAXCL)
			ncl = MAXCL;
		if (scanf("%15s", tag) != 1 || strcmp(tag, "V") != 0 || !read_site(vxyz, vod))
			break;
		for (k = 0; k < ncl; k++)
			if (scanf("%15s", tag) != 1 || strcmp(tag, "C") != 0 ||
			    !read_site(cxyz[k], cod[k]))
				break;
		if (k != ncl)
			break;

		t = epoch2time((double[]){2024, 10, 10, 0, 0, 0});
		for (step = 0; step < SPAN_DAYS * 86400 / (int)STEP_S; step++,
		    t = timeadd(t, STEP_S)) {
			double dv[3], dvenu[3], pos[3], de[MAXCL], dn[MAXCL];
			double comp[3][MAXCL], d[3], denu[3], dr[3];

			ecef2pos(vxyz, pos);
			tidedisp(t, vxyz, opt, &erp, vod, dv);
			ecef2enu(pos, dv, dvenu);

			for (k = 0; k < ncl; k++) {
				double rel[3];

				tidedisp(t, cxyz[k], opt, &erp, cod[k], d);
				ecef2enu(pos, d, denu);
				for (i = 0; i < 3; i++) {
					comp[i][k] = denu[i];
					rel[i] = cxyz[k][i] - vxyz[i];
				}
				ecef2enu(pos, rel, dr);
				de[k] = dr[0] / 1000.0;	/* km: keeps the normal matrix sane */
				dn[k] = dr[1] / 1000.0;
			}
			for (i = 0; i < 3; i++) {
				double v = fabs(dvenu[i] - comp[i][0]) * 1000.0;

				if (v > raw[i])
					raw[i] = v;
				v = fabs(dvenu[i] -
				    planefit_at_vbs(de, dn, comp[i], ncl, &lev)) * 1000.0;
				if (v > res[i])
					res[i] = v;
			}
		}
		printf("%-8s %-10s %3d  %7.2f %7.2f %7.2f  %7.2f %7.2f %7.2f %6.2f\n",
		    id, label, ncl, raw[0], raw[1], raw[2], res[0], res[1], res[2], lev);
		fflush(stdout);
	}
	return 0;
}
